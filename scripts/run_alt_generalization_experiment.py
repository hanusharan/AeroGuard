"""Generalization experiment, Phase 4 (part 2) — the actual test.

FORWARD DIRECTION (primary result): evaluate the FROZEN v0.3 primary
model (outputs/ml_v03/models/primary_model_D_1s.joblib, never refit here)
on the alternative-mechanism "holdout" trajectories generated by
scripts/generate_alt_single_dataset.py -- data the model has never seen
in any form (the mechanism did not exist when that model was trained).

REVERSE DIRECTION (cheap, secondary check): fit ONE fresh RandomForest
(same frozen hyperparameters, same feature set, same TRAIN-then-VAL
threshold procedure -- ml/temporal_experiment.py's fit_rf_and_threshold,
reused unchanged) on the alternative mechanism's own train/val
trajectories, then evaluate it -- unchanged -- on the FROZEN v0.3 TEST
split's gradual_approach_v3-only rows (data/ml_temporal_v03/temporal_test
.parquet, read-only, never modified).

Both directions reuse ml/temporal_features.py's build_temporal_panel /
usable_mask_for_window and ml/temporal_experiment.py's get_xy /
evaluate_on_test UNCHANGED -- the exact same feature definitions,
leakage guard, and event/lead-time computation as the v0.2 and v0.3
experiments, per the task's explicit "same frozen feature definitions
and evaluation methodology" instruction.

Does NOT modify aeroguard/, aeroguard_dataset/, data/, outputs/ml_v03/,
outputs/ml_temporal/, or any existing report. Writes only to
outputs/ml_v03_generalization/metrics/ and .../plots/ (new, isolated).

Run with:
    python scripts/run_alt_generalization_experiment.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from aeroguard_dataset import paths
from aeroguard_dataset.features import causal_backward_difference
from ml import temporal_config_v03 as v3cfg
from ml.temporal_data_v03 import load_temporal_splits
from ml.temporal_experiment import (
    NumpyJSONEncoder,
    evaluate_on_test,
    fit_rf_and_threshold,
    get_xy,
)
from ml.temporal_features import build_temporal_panel, usable_mask_for_window

_SCRIPTS_DIR = os.path.join(v3cfg.PROJECT_ROOT, "scripts")
if _SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, _SCRIPTS_DIR)
from prepare_ml_dataset import compute_time_to_stall  # noqa: E402

GEN_DIR = os.path.join(paths.OUTPUTS_DIR, "ml_v03_generalization")
DATA_DIR = os.path.join(GEN_DIR, "data")
METRICS_DIR = os.path.join(GEN_DIR, "metrics")
PLOTS_DIR = os.path.join(GEN_DIR, "plots")
os.makedirs(METRICS_DIR, exist_ok=True)
os.makedirs(PLOTS_DIR, exist_ok=True)

WINDOW_S = 1.0  # matches v0.3's primary model window
GRADUAL_V3_REGIME = "gradual_approach_v3"
ALT_REGIME = "gradual_alt_single_capped"


def _prep_panel(processed_df: pd.DataFrame) -> pd.DataFrame:
    """Mirrors ml/temporal_data_v03.py's _load_full_processed_with_split
    (minus the split-manifest merge, which callers handle themselves) so
    the alt-mechanism data gets EXACTLY the same derived columns
    (dgamma_dt, dq_dt, time_to_stall) as the v0.3 pipeline before
    build_temporal_panel is applied."""
    df = processed_df.sort_values(["trajectory_id", "time"]).reset_index(drop=True)
    df["dgamma_dt"] = df.groupby("trajectory_id")["gamma"].transform(
        lambda s: causal_backward_difference(s.to_numpy(), v3cfg.DT))
    df["dq_dt"] = df.groupby("trajectory_id")["pitch_rate"].transform(
        lambda s: causal_backward_difference(s.to_numpy(), v3cfg.DT))
    df["time_to_stall"] = compute_time_to_stall(df)
    panel = build_temporal_panel(df, windows_s=v3cfg.HISTORY_WINDOWS_S, dt=v3cfg.DT)
    return panel


def row_level_fpr(test_metrics: dict) -> float:
    cm = test_metrics["confusion_matrix"]
    fp, tn = cm["fp"], cm["tn"]
    return float(fp / (fp + tn)) if (fp + tn) > 0 else float("nan")


def warning_coverage_from_result(res: dict) -> dict:
    return res.get("fraction_of_events_detected_at_least", {})


def main():
    print("=== FORWARD DIRECTION: frozen v0.3 primary model -> alt-mechanism holdout ===")
    holdout_processed = pd.read_parquet(os.path.join(DATA_DIR, "alt_holdout_processed.parquet"))
    holdout_panel = _prep_panel(holdout_processed)
    holdout_mask = usable_mask_for_window(holdout_panel, WINDOW_S)
    feats = v3cfg.model_d_features(WINDOW_S)
    X_holdout, y_holdout, holdout_sub = get_xy(holdout_panel, feats, holdout_mask)
    print(f"  alt holdout usable rows: {len(X_holdout):,} "
          f"({holdout_panel.loc[holdout_mask, 'trajectory_id'].nunique()}/{holdout_panel['trajectory_id'].nunique()} trajectories)")

    frozen_model = joblib.load(os.path.join(v3cfg.MODELS_DIR, "primary_model_D_1s.joblib"))
    with open(os.path.join(v3cfg.METRICS_DIR, "primary_model_metrics.json")) as f:
        frozen_metrics = json.load(f)
    frozen_threshold = frozen_metrics["threshold"]
    assert frozen_metrics["feature_columns"] == feats, "feature set mismatch vs. the frozen v0.3 primary model"

    forward_res, forward_proba, forward_pred = evaluate_on_test(frozen_model, frozen_threshold, X_holdout, y_holdout, holdout_sub)
    forward_res["row_level_false_positive_rate"] = row_level_fpr(forward_res["test_metrics"])
    forward_res["description"] = (
        "Frozen v0.3 primary model (outputs/ml_v03/models/primary_model_D_1s.joblib, NOT refit), "
        "evaluated on trajectories from the alternative single-pulse duration-capped precursor "
        "mechanism (aeroguard_dataset/control_profiles_alt_single.py) -- none of these trajectories "
        "existed anywhere in the model's training data."
    )
    print(f"  PR-AUC={forward_res['test_metrics']['pr_auc']:.4f}  recall={forward_res['test_metrics']['recall']:.4f}  "
          f"event_recall={forward_res['event_level']['event_recall']:.4f}  "
          f"median_lead={forward_res['event_level']['median_lead_time_s']:.2f}s  "
          f"row_FPR={forward_res['row_level_false_positive_rate']:.4f}")

    with open(os.path.join(METRICS_DIR, "forward_check_frozen_model_on_alt_mechanism.json"), "w") as f:
        json.dump(forward_res, f, indent=2, cls=NumpyJSONEncoder)

    print("\n=== REVERSE DIRECTION: model trained on alt-mechanism -> frozen v0.3 gradual_approach_v3 test rows ===")
    tv_processed = pd.read_parquet(os.path.join(DATA_DIR, "alt_trainval_processed.parquet"))
    tv_manifest = pd.read_csv(os.path.join(DATA_DIR, "alt_trainval_split_manifest.csv"))
    tv_panel = _prep_panel(tv_processed)
    n_before = len(tv_panel)
    tv_panel = tv_panel.merge(tv_manifest, on="trajectory_id", how="left", validate="many_to_one")
    assert len(tv_panel) == n_before and tv_panel["split"].notna().all()

    tv_train = tv_panel[tv_panel["split"] == "train"].reset_index(drop=True)
    tv_val = tv_panel[tv_panel["split"] == "val"].reset_index(drop=True)
    train_mask = usable_mask_for_window(tv_train, WINDOW_S)
    val_mask = usable_mask_for_window(tv_val, WINDOW_S)
    Xtr, ytr, _ = get_xy(tv_train, feats, train_mask)
    Xv, yv, _ = get_xy(tv_val, feats, val_mask)
    print(f"  alt train/val usable rows: train={len(Xtr):,} val={len(Xv):,}")

    alt_model, alt_threshold, alt_thr_info = fit_rf_and_threshold(Xtr, ytr, Xv, yv, v3cfg.FROZEN_RF_PARAMS)

    v03_splits = load_temporal_splits(force=False, verbose=False)  # reuses the existing frozen cache, read-only
    v03_test = v03_splits["test"]
    v03_meta = pd.read_csv(v3cfg.METADATA_PATH)[["trajectory_id", "generation_mode"]]
    v03_test_regime = v03_test.merge(v03_meta, on="trajectory_id", how="left")
    gradual_test = v03_test_regime[v03_test_regime["generation_mode"] == GRADUAL_V3_REGIME].reset_index(drop=True)
    gradual_mask = usable_mask_for_window(gradual_test, WINDOW_S)
    Xte, yte, test_sub = get_xy(gradual_test, feats, gradual_mask)
    print(f"  frozen v0.3 TEST gradual_approach_v3-only usable rows: {len(Xte):,} "
          f"({gradual_test.loc[gradual_mask, 'trajectory_id'].nunique()}/{gradual_test['trajectory_id'].nunique()} trajectories)")

    reverse_res, reverse_proba, reverse_pred = evaluate_on_test(alt_model, alt_threshold, Xte, yte, test_sub)
    reverse_res["row_level_false_positive_rate"] = row_level_fpr(reverse_res["test_metrics"])
    reverse_res["train_population"] = {"n_rows": int(len(Xtr)), "n_trajectories": int(tv_train.loc[train_mask, "trajectory_id"].nunique())}
    reverse_res["description"] = (
        "Fresh RandomForest (same frozen hyperparameters/features/threshold procedure as every other "
        "v0.3 model), trained ONLY on the alternative single-pulse mechanism's own train/val trajectories, "
        "evaluated on the FROZEN v0.3 TEST split's gradual_approach_v3-regime rows only (never touched "
        "during this model's training)."
    )
    print(f"  PR-AUC={reverse_res['test_metrics']['pr_auc']:.4f}  recall={reverse_res['test_metrics']['recall']:.4f}  "
          f"event_recall={reverse_res['event_level']['event_recall']:.4f}  "
          f"median_lead={reverse_res['event_level']['median_lead_time_s']:.2f}s  "
          f"row_FPR={reverse_res['row_level_false_positive_rate']:.4f}")

    with open(os.path.join(METRICS_DIR, "reverse_check_alt_model_on_v03_gradual.json"), "w") as f:
        json.dump(reverse_res, f, indent=2, cls=NumpyJSONEncoder)

    # ---- comparison table against existing (read-only reference) v0.3 numbers ----
    with open(os.path.join(v3cfg.METRICS_DIR, "generalization_check.json")) as f:
        v03_gen_check = json.load(f)  # v0.3's own check: exclude gradual_approach_v3 from TRAIN, test on full TEST

    comparison_rows = [
        {
            "experiment": "v0.3 in-distribution (primary model, own test population)",
            "pr_auc": frozen_metrics["test_metrics"]["pr_auc"],
            "event_recall": frozen_metrics["event_level"]["event_recall"],
            "median_lead_time_s": frozen_metrics["event_level"]["median_lead_time_s"],
            "warning_coverage_ge2s": frozen_metrics["fraction_of_events_detected_at_least"].get(">=2s"),
            "warning_coverage_ge4s": frozen_metrics["fraction_of_events_detected_at_least"].get(">=4s"),
        },
        {
            "experiment": "v0.3 regime-exclusion check (gradual_approach_v3 excluded from TRAIN, full TEST)",
            "pr_auc": v03_gen_check["test_metrics"]["pr_auc"],
            "event_recall": v03_gen_check["event_level"]["event_recall"],
            "median_lead_time_s": v03_gen_check["event_level"]["median_lead_time_s"],
            "warning_coverage_ge2s": v03_gen_check["fraction_of_events_detected_at_least"].get(">=2s"),
            "warning_coverage_ge4s": v03_gen_check["fraction_of_events_detected_at_least"].get(">=4s"),
        },
        {
            "experiment": "FORWARD: frozen v0.3 model -> novel alt-mechanism trajectories",
            "pr_auc": forward_res["test_metrics"]["pr_auc"],
            "event_recall": forward_res["event_level"]["event_recall"],
            "median_lead_time_s": forward_res["event_level"]["median_lead_time_s"],
            "warning_coverage_ge2s": forward_res["fraction_of_events_detected_at_least"].get(">=2s"),
            "warning_coverage_ge4s": forward_res["fraction_of_events_detected_at_least"].get(">=4s"),
        },
        {
            "experiment": "REVERSE: alt-mechanism-trained model -> held-out gradual_approach_v3",
            "pr_auc": reverse_res["test_metrics"]["pr_auc"],
            "event_recall": reverse_res["event_level"]["event_recall"],
            "median_lead_time_s": reverse_res["event_level"]["median_lead_time_s"],
            "warning_coverage_ge2s": reverse_res["fraction_of_events_detected_at_least"].get(">=2s"),
            "warning_coverage_ge4s": reverse_res["fraction_of_events_detected_at_least"].get(">=4s"),
        },
    ]
    comparison_df = pd.DataFrame(comparison_rows)
    comparison_df.to_csv(os.path.join(METRICS_DIR, "cross_mechanism_comparison.csv"), index=False)
    print("\n=== Comparison table ===")
    print(comparison_df.to_string(index=False))

    # ---- plot: lead-time recall bucket comparison ----
    fig, ax = plt.subplots(figsize=(8, 5))
    buckets = [r["bucket"] for r in frozen_metrics["lead_time_recall_bucket"]]
    x = np.arange(len(buckets))
    width = 0.35
    in_dist = [r["recall"] for r in frozen_metrics["lead_time_recall_bucket"]]
    forward_recall = [r["recall"] for r in forward_res["lead_time_recall_bucket"]]
    ax.bar(x - width / 2, in_dist, width, label="v0.3 in-distribution (gradual_approach_v3-trained)")
    ax.bar(x + width / 2, forward_recall, width, label="frozen model -> novel alt mechanism (forward check)")
    ax.set_xticks(x)
    ax.set_xticklabels(buckets, rotation=30)
    ax.set_ylabel("row-level recall")
    ax.set_title("Lead-time recall: in-distribution vs. novel-mechanism generalization")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOTS_DIR, "01_lead_time_recall_forward_check.png"), dpi=120)
    plt.close(fig)

    summary = {
        "window_s": WINDOW_S, "feature_columns": feats,
        "forward_check_holdout_population": {
            "n_trajectories": int(holdout_panel["trajectory_id"].nunique()),
            "n_crossing_trajectories": int(pd.read_csv(os.path.join(DATA_DIR, "alt_holdout_metadata.csv"))["whether_stall_occurred"].sum()),
            "n_usable_rows": int(len(X_holdout)),
            "n_events": forward_res["event_level"]["n_events"],
        },
        "reverse_check_train_population": reverse_res["train_population"],
        "reverse_check_test_population": {
            "n_trajectories": int(gradual_test["trajectory_id"].nunique()),
            "n_usable_rows": int(len(Xte)),
            "n_events": reverse_res["event_level"]["n_events"],
        },
    }
    with open(os.path.join(METRICS_DIR, "experiment_summary.json"), "w") as f:
        json.dump(summary, f, indent=2, cls=NumpyJSONEncoder)

    print(f"\nDone. Outputs in {METRICS_DIR} and {PLOTS_DIR}")


if __name__ == "__main__":
    main()
