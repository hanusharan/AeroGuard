"""Generalization-experiment ALTERNATIVE gradual-stall precursor
mechanism ("Candidate F: single-pulse, duration-capped").

Purpose: outputs/ml_v03_generalization/ needs ONE control-profile
mechanism that is structurally different from the locked v0.3
Candidate D (control_profiles_candidate_d_v3.py) -- not a re-parameterized
copy of it -- so that evaluating the frozen v0.3 primary model on
trajectories generated by THIS mechanism is a meaningful test of whether
the model learned transferable "rising alpha toward a shrinking margin"
physics, rather than the specific two-pulse D-shaped morphology.

Does NOT modify aeroguard/ physics, aeroguard_dataset/config.py,
aeroguard_dataset/control_profiles.py, control_profiles_candidate_d_v2.py,
or control_profiles_candidate_d_v3.py. Purely additive.

MECHANISM: reuses GRADUAL_A_TIGHT_MARGIN's already-calibrated elevator
spec (config.py) -- a single elevator pulse (rise 3.0-4.5s, hold
0.5-2.0s, fall 1.0-2.0s, magnitude 0.07-0.10 rad; implied alpha_eq
~22.4-32.0deg, comfortably past the ~16.07deg boundary) -- UNCHANGED,
not redefined here. In the ORIGINAL 5-candidate calibration
(outputs/v03_calibration/decision_gate_report.md), this single-pulse
family (A/B/C) produced good precursor statistics but suffered from
"sustained TIME at elevated alpha" driving 63-91% gamma-envelope
terminations, because the pulse's rise+hold+fall was left uncapped.
Candidate D's OWN documented fix for that exact failure mode
(control_profiles_candidate_d_v3.py's cap_total_pulse_duration:
"gamma accumulates with exposure duration, not amplitude" -- trim HOLD
time first, down to a floor of 0, before ever touching rise/fall) is
reused here IN CONCEPT (same idea, independently re-implemented for a
single pulse rather than two) to fix the single-pulse family's own
gamma-runaway problem, without borrowing D's two-pulse
same-sign/zero-gap sequencing at all.

This gives a genuinely distinct temporal signature: D's alpha response is
a two-stage "staircase" (rise-partial-fall-rise-fall, because pulse 2
starts as soon as pulse 1's command returns to zero); this mechanism's
alpha response is a single smooth monotonic rise to one plateau and one
decline -- a "single-hump" approach, not a staircase -- while using the
SAME aeroguard/ physics, the SAME pitch model, and the SAME
CL(alpha)-peak stall boundary (aeroguard_dataset.events.StallBoundary).
No dive-then-zoom is structurally possible (a single pulse cannot flip
sign against itself the way two independently-signed pulses could).
"""
from typing import List

import numpy as np

from aeroguard_dataset.config import ControlRangeSpec, GRADUAL_A_TIGHT_MARGIN
from aeroguard_dataset.control_profiles import ControlProfile, Pulse, sample_pulses

ALT_SINGLE_ELEVATOR_SPEC: ControlRangeSpec = GRADUAL_A_TIGHT_MARGIN.elevator

# Chosen from the same logic as Candidate D v3's 7.0s cap (see that
# module's docstring): the single-pulse family's uncapped max total is
# rise_max + hold_max + fall_max = 4.5 + 2.0 + 2.0 = 8.5s. A 6.0s cap
# leaves the full rise+fall range (4.0-6.5s) mostly intact (only the
# rise+fall-max case loses a little to the cap, since only hold is ever
# trimmed) while removing most or all of the hold phase that the
# original calibration diagnosed as the gamma-accumulation driver.
TOTAL_DURATION_CAP_S = 6.0


def cap_single_pulse_duration(pulse: Pulse, cap_s: float = TOTAL_DURATION_CAP_S) -> Pulse:
    """Trim `pulse.hold` down to a floor of 0 until rise+hold+fall <=
    cap_s. Rise and fall are never touched (same policy as Candidate D
    v3's cap_total_pulse_duration, applied to one pulse instead of
    two)."""
    total = pulse.rise + pulse.hold + pulse.fall
    excess = total - cap_s
    if excess <= 0:
        return pulse
    trim = min(pulse.hold, excess)
    return Pulse(start=pulse.start, rise=pulse.rise, hold=pulse.hold - trim, fall=pulse.fall, magnitude=pulse.magnitude)


def sample_capped_single_pulse(rng: np.random.Generator, spec: ControlRangeSpec, duration_s: float,
                                cap_s: float = TOTAL_DURATION_CAP_S) -> List[Pulse]:
    pulses = sample_pulses(rng, spec, n_pulses=1, duration_s=duration_s)
    return [cap_single_pulse_duration(p, cap_s) for p in pulses]


def build_alt_single_pulse_profile(
    rng: np.random.Generator, alpha_trim: float, throttle_trim: float, elevator_trim: float, duration_s: float,
    cap_s: float = TOTAL_DURATION_CAP_S,
) -> ControlProfile:
    """Elevator-only (throttle inert for alpha in this model -- confirmed
    in config.py's v0.3-candidates note; matches every other
    gradual-approach candidate's own choice not to perturb throttle)."""
    elevator_pulses = sample_capped_single_pulse(rng, ALT_SINGLE_ELEVATOR_SPEC, duration_s, cap_s)
    return ControlProfile(
        elevator_trim=elevator_trim, throttle_trim=throttle_trim,
        elevator_pulses=elevator_pulses, throttle_pulses=[],
    )
